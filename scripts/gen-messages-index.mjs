// Writes src/lib/i18n/messages/index.ts from LOCALES in src/lib/i18n/config.ts
// and the area files in messages/en. Run it after adding a language folder and
// its code to LOCALES (the bundler needs every JSON file imported by name).
//
//   node scripts/gen-messages-index.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const base = "src/lib/i18n/messages";
const config = readFileSync("src/lib/i18n/config.ts", "utf8");
const locales = JSON.parse(config.match(/export const LOCALES = (\[[^\]]*\])/)[1].replace(/'/g, '"'));
const areas = readdirSync(`${base}/en`)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();
const ident = (locale, area) => `${locale.replace(/-/g, "")}${area[0].toUpperCase()}${area.slice(1)}`;

for (const locale of locales) for (const area of areas) if (!existsSync(`${base}/${locale}/${area}.json`)) throw new Error(`missing ${locale}/${area}.json`);

const lines = [
  "// Every language's text, one file per area of the app. Keys are \"area.key\";",
  "// each area's file holds the part after the dot.",
  "// Generated by scripts/gen-messages-index.mjs: run it after adding a language.",
  'import type { Locale } from "../config";',
  "",
  ...locales.flatMap((locale) => areas.map((area) => `import ${ident(locale, area)} from "./${locale}/${area}.json";`)),
  "",
  "export type Messages = Record<string, string>;",
  "",
  "const flatten = (areas: Record<string, Record<string, string>>): Messages =>",
  "  Object.fromEntries(Object.entries(areas).flatMap(([area, entries]) => Object.entries(entries).map(([key, text]) => [`${area}.${key}`, text])));",
  "",
  "export const MESSAGES: Record<Locale, Messages> = {",
  ...locales.map((locale) => `  ${/^[a-z]+$/.test(locale) ? locale : JSON.stringify(locale)}: flatten({ ${areas.map((a) => `${a}: ${ident(locale, a)}`).join(", ")} }),`),
  "};",
  "",
];
writeFileSync(`${base}/index.ts`, lines.join("\n"));
console.log(`index.ts: ${locales.length} languages x ${areas.length} areas`);
