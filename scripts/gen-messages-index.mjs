// Writes src/lib/i18n/messages/bundles/<language>.ts (one language's areas,
// flattened) and src/lib/i18n/messages/index.ts (loads a language the first
// time it is asked for). Run it after adding a language or an area:
//
//   node scripts/gen-messages-index.mjs
//
// Each language is its own module, loaded on demand, so a server start-up
// or a page evaluates only the languages in use rather than all of them.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const base = "src/lib/i18n/messages";
const config = readFileSync("src/lib/i18n/config.ts", "utf8");
const locales = JSON.parse(config.match(/export const LOCALES = (\[[^\]]*\])/)[1].replace(/'/g, '"'));
const areas = readdirSync(`${base}/en`)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();
const ident = (area) => `${area[0]}${area.slice(1)}`;
for (const locale of locales) for (const area of areas) if (!existsSync(`${base}/${locale}/${area}.json`)) throw new Error(`missing ${locale}/${area}.json`);

mkdirSync(`${base}/bundles`, { recursive: true });
for (const locale of locales) {
  const lines = [
    `// ${locale}: every area's text, flattened to "area.key". Generated by scripts/gen-messages-index.mjs.`,
    `import { flatten } from "../flatten";`,
    "",
    ...areas.map((area) => `import ${ident(area)} from "../${locale}/${area}.json";`),
    "",
    `export default flatten({ ${areas.map((a) => `${a}: ${ident(a)}`).join(", ")} });`,
    "",
  ];
  writeFileSync(`${base}/bundles/${locale}.ts`, lines.join("\n"));
}

const key = (locale) => (/^[a-z]+$/.test(locale) ? locale : JSON.stringify(locale));
const index = [
  "// Every language's text, one module per language, loaded the first time it",
  "// is asked for and kept. Keys are \"area.key\"; each area's file holds the part",
  "// after the dot. Generated by scripts/gen-messages-index.mjs: run it after adding a language.",
  'import type { Locale } from "../config";',
  'import type { Messages } from "./flatten";',
  "",
  'export type { Messages } from "./flatten";',
  "",
  "const LOADERS: Record<Locale, () => Promise<{ default: Messages }>> = {",
  ...locales.map((locale) => `  ${key(locale)}: () => import("./bundles/${locale}"),`),
  "};",
  "",
  "const loaded = new Map<Locale, Promise<Messages>>();",
  "",
  "/** One language's text, loaded on first use and kept for the life of the process. */",
  "export function loadMessages(locale: Locale): Promise<Messages> {",
  "  let messages = loaded.get(locale);",
  "  if (!messages) {",
  "    messages = LOADERS[locale]().then((m) => m.default);",
  "    messages.catch(() => loaded.delete(locale)); // a failed load is not remembered",
  "    loaded.set(locale, messages);",
  "  }",
  "  return messages;",
  "}",
  "",
];
writeFileSync(`${base}/index.ts`, index.join("\n"));
console.log(`messages: ${locales.length} languages x ${areas.length} areas`);
